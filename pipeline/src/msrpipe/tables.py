"""Step `tables`: LaTeX tables for the paper from the aggregated analysis output.

Reads only per-platform aggregates in /data/analysis/<freeze-date>/ (no repo names, paths
or code) and writes .tex files to /tables (paper/tables). Numbers are never typed by hand.
"""

import csv
from decimal import ROUND_HALF_UP, Decimal, localcontext
from fractions import Fraction
from pathlib import Path

from . import config
from .analyse import PLATFORMS, SEVERITIES, quartiles
from .review import wilson
from .validate import pools

PLATFORM_NAMES = {"lovable": "Lovable", "replit": "Replit", "boltnew": "Bolt.new"}


def read(path):
    with open(path, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def category_name(cat):
    """'A01:2025' -> 'A01 Broken Access Control' from the OWASP file names in config."""
    if cat == config.OWASP_UNMAPPED:
        return "Not in Top 10:2025"
    name = config.OWASP_2025[cat].split("-", 1)[1].replace("_", " ")
    return f"{cat.split(':')[0]} {name}"


def num(n):
    return f"{int(n):,}"


def _round(x, places):
    """Round half up from the exact value: a Fraction (from counts) or a float computed at full
    precision. Shares are computed from counts here, not from the 4-decimal shares in the CSV
    files, to avoid double rounding (e.g. 405/3,856 = 10.503 % was shown as 10 %)."""
    with localcontext() as ctx:
        ctx.prec = 50
        d = (Decimal(x.numerator) / Decimal(x.denominator) if isinstance(x, Fraction)
             else Decimal(float(x)))
        return d.quantize(Decimal(1).scaleb(-places), rounding=ROUND_HALF_UP)


def share(n, d):
    return Fraction(int(n), int(d)) if int(d) else Fraction(0)


def pct(x):
    return f"{_round(Fraction(x) * 100 if isinstance(x, Fraction) else float(x) * 100, 0)}\\,\\%"


def rq1_category(rows, totals, n_repos, tool="combined"):
    """rows: rq1_category.csv; totals: platform -> unique findings for `tool`;
    n_repos: platform -> repositories in the sample. Shares are computed from the counts."""
    by = {(r["platform"], r["category"]): r for r in rows if r["tool"] == tool}
    cats = list(config.OWASP_2025) + [config.OWASP_UNMAPPED]
    head = " & ".join(f"\\multicolumn{{2}}{{c}}{{\\textbf{{{PLATFORM_NAMES[p]}}}}}" for p in PLATFORMS)
    sub = " & ".join(["Findings & Repos"] * len(PLATFORMS))
    lines = [
        "% Generated by `docker compose run --rm pipeline tables` from rq1_category.csv; do not edit.",
        "\\begin{table*}[t]",
        "\\centering",
        "\\footnotesize",
        "\\caption{Findings per OWASP Top~10:2025 category and platform (CodeQL and GitLab SAST combined, "
        "deduplicated). Findings: number and share of the platform's unique findings; a finding whose CWEs "
        "map to several categories is counted in each, so the shares can sum to more than 100\\,\\%. "
        "Repos: share of the 50 repositories with at least one finding in the category.}",
        "\\label{tab:rq1-category}",
        "\\begin{tabular}{@{}l" + "rr" * len(PLATFORMS) + "@{}}",
        "\\toprule",
        f"\\textbf{{Category}} & {head} \\\\",
        "".join(f"\\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(len(PLATFORMS))),
        f" & {sub} \\\\",
        "\\midrule",
    ]
    for c in cats:
        cells = []
        for p in PLATFORMS:
            r = by[(p, c)]
            cells.append(f"{num(r['findings'])} ({pct(share(r['findings'], totals[p]))}) & "
                         f"{pct(share(r['repos'], n_repos[p]))}")
        if c == config.OWASP_UNMAPPED:
            lines.append("\\midrule")
        lines.append(f"{category_name(c)} & " + " & ".join(cells) + " \\\\")
    lines += [
        "\\midrule",
        "Unique findings & " + " & ".join(f"{num(totals[p])} & " for p in PLATFORMS) + " \\\\",
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table*}",
    ]
    return "\n".join(lines) + "\n"


SEVERITY_TOOLS = [("combined", "Comb."), ("codeql", "CodeQL"), ("gitlab", "GitLab")]


def rq1_severity(rows):
    """rows: rq1_severity.csv -> severity per platform: combined (n and share), CodeQL and GitLab (n).
    Severity levels with no finding for any platform and tool are left out."""
    tools = [t for t, _ in SEVERITY_TOOLS]
    by = {(r["platform"], r["tool"], r["severity"]): r for r in rows if r["tool"] in tools}
    levels = [s for s in SEVERITIES
              if any(int(by[(p, t, s)]["findings"]) for p in PLATFORMS for t in tools)]
    total = {(p, t): sum(int(by[(p, t, s)]["findings"]) for s in SEVERITIES)
             for p in PLATFORMS for t in tools}
    ncol = len(SEVERITY_TOOLS)
    head = " & ".join(f"\\multicolumn{{{ncol}}}{{c}}{{\\textbf{{{PLATFORM_NAMES[p]}}}}}" for p in PLATFORMS)
    sub = " & ".join([" & ".join(lbl for _, lbl in SEVERITY_TOOLS)] * len(PLATFORMS))
    lines = [
        "% Generated by `docker compose run --rm pipeline tables` from rq1_severity.csv; do not edit.",
        "\\begin{table*}[t]",
        "\\centering",
        "\\footnotesize",
        "\\caption{Findings per severity and platform. Comb.: CodeQL and GitLab SAST combined and "
        "deduplicated (number and share); a matched pair keeps the higher severity. CodeQL: "
        "\\texttt{security-severity} mapped to the CVSS~v3.1 qualitative scale. GitLab: the severity in "
        "GitLab's report. Severity levels without findings are omitted.}",
        "\\label{tab:rq1-severity}",
        "\\begin{tabular}{@{}l" + "rrr" * len(PLATFORMS) + "@{}}",
        "\\toprule",
        f"\\textbf{{Severity}} & {head} \\\\",
        "".join(f"\\cmidrule(lr){{{2 + ncol * i}-{1 + ncol * (i + 1)}}}" for i in range(len(PLATFORMS))),
        f" & {sub} \\\\",
        "\\midrule",
    ]
    for s in levels:
        cells = []
        for p in PLATFORMS:
            c = by[(p, "combined", s)]
            cells.append(f"{num(c['findings'])} ({pct(share(c['findings'], total[(p, 'combined')]))})")
            cells += [num(by[(p, t, s)]["findings"]) for t in tools[1:]]
        lines.append(f"{s} & " + " & ".join(cells) + " \\\\")
    lines += [
        "\\midrule",
        "Total & " + " & ".join(num(total[(p, t)]) for p in PLATFORMS for t in tools) + " \\\\",
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table*}",
    ]
    return "\n".join(lines) + "\n"


PRECISION_TOOLS = [("codeql", "CodeQL"), ("gitlab", "GitLab SAST")]


def ratio(x):
    return str(_round(x, 2))


def review_precision(rows):
    """rows: review_precision.csv (one row per platform x tool) -> TP/FP/unclear and precision [95% CI]."""
    by = {(r["platform"], r["tool"]): r for r in rows}
    head = " & ".join(f"\\multicolumn{{4}}{{c}}{{\\textbf{{{lbl}}}}}" for _, lbl in PRECISION_TOOLS)
    sub = " & ".join(["TP & FP & Uncl. & Precision [95\\,\\% CI]"] * len(PRECISION_TOOLS))
    lines = [
        "% Generated by `docker compose run --rm pipeline tables` from review_precision.csv; do not edit.",
        "\\begin{table*}[t]",
        "\\centering",
        "\\footnotesize",
        "\\caption{Manual assessment of a stratified random sample of 20 findings per platform and tool. "
        "Precision = TP/(TP+FP) with a Wilson 95\\,\\% confidence interval; unclear findings are excluded "
        "from the precision. Labels by the author.}",
        "\\label{tab:review-precision}",
        "\\begin{tabular}{@{}l" + "rrrr" * len(PRECISION_TOOLS) + "@{}}",
        "\\toprule",
        f"\\textbf{{Platform}} & {head} \\\\",
        "".join(f"\\cmidrule(lr){{{2 + 4 * i}-{5 + 4 * i}}}" for i in range(len(PRECISION_TOOLS))),
        f" & {sub} \\\\",
        "\\midrule",
    ]
    for p in PLATFORMS:
        cells = []
        for t, _ in PRECISION_TOOLS:
            r = by[(p, t)]
            tp, fp = int(r["TP"]), int(r["FP"])
            lo, hi = wilson(tp, tp + fp, places=None)   # from the counts, not the rounded CSV values
            cells += [r["TP"], r["FP"], r["uklar"],
                      f"{ratio(share(tp, tp + fp))} [{ratio(lo)}--{ratio(hi)}]"]
        lines.append(f"{PLATFORM_NAMES[p]} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}"]
    return "\n".join(lines) + "\n"


MARKERS = [("other_ai_tool", "Other AI coding tool"),
           ("ambiguous_instructions", "\\texttt{AGENTS.md} or \\texttt{CLAUDE.md}"),
           ("other_platform", "Other vibe coding platform")]


def markers(samples):
    """samples: platform -> main-sample rows from screen_<platform>.csv -> repos with each marker
    variable (n and share) and the platform's share of commits (median [Q1-Q3]; none for Bolt.new)."""
    lines = [
        "% Generated by `docker compose run --rm pipeline tables` from screen_<platform>.csv "
        "(main sample); do not edit.",
        "\\begin{table}[t]",
        "\\centering",
        "\\footnotesize",
        "\\caption{Variables recorded for the repositories in the main sample (50 per platform); they do "
        "not exclude repositories. Marker rows: repositories with at least one marker file anywhere in "
        "the tree. Platform commit share: median [Q1--Q3] of the share of commits by the platform's "
        "identity; not available for Bolt.new, which commits under the user's account.}",
        "\\label{tab:markers}",
        "\\begin{tabular}{@{}l" + "r" * len(PLATFORMS) + "@{}}",
        "\\toprule",
        " & " + " & ".join(f"\\textbf{{{PLATFORM_NAMES[p]}}}" for p in PLATFORMS) + " \\\\",
        "\\midrule",
    ]
    for key, label in MARKERS:
        cells = []
        for p in PLATFORMS:
            rows = samples[p]
            n = sum(bool(r[key]) for r in rows)
            cells.append(f"{n} ({pct(share(n, len(rows)))})")
        lines.append(f"{label} & " + " & ".join(cells) + " \\\\")
    cells = []
    for p in PLATFORMS:
        shares = [float(r["platform_share"]) for r in samples[p] if r["platform_share"]]
        if shares:
            q1, q2, q3 = quartiles(shares)
            cells.append(f"{pct(q2)} [{pct(q1)}--{pct(q3)}]")
        else:
            cells.append("--")
    lines += ["\\midrule", "Platform commit share & " + " & ".join(cells) + " \\\\",
              "\\bottomrule", "\\end{tabular}", "\\end{table}"]
    return "\n".join(lines) + "\n"


DENSITY_TOOLS = [("combined", "Combined"), ("codeql", "CodeQL"), ("gitlab", "GitLab SAST")]


def rq2_density(rows, repos):
    """rows: rq2_density.csv (KLOC and repos with zero findings); repos: repos.csv. The median and
    quartiles are computed here from each repo's count and KLOC, not from the rounded CSV values."""
    by = {(r["platform"], r["tool"]): r for r in rows}
    dens = {(p, t): [int(r[f"n_{t}"]) / float(r["kloc"]) for r in repos if r["platform"] == p]
            for p in PLATFORMS for t, _ in DENSITY_TOOLS}
    head = " & ".join(f"\\multicolumn{{2}}{{c}}{{\\textbf{{{lbl}}}}}" for _, lbl in DENSITY_TOOLS)
    sub = " & ".join(["Median [Q1--Q3] & Zero"] * len(DENSITY_TOOLS))
    lines = [
        "% Generated by `docker compose run --rm pipeline tables` from rq2_density.csv; do not edit.",
        "\\begin{table*}[t]",
        "\\centering",
        "\\footnotesize",
        "\\caption{Findings per KLOC per repository (50 per platform): median and interquartile range "
        "[Q1--Q3], and the number of repositories without findings (Zero). KLOC: lines of code in "
        "JavaScript, TypeScript, JSX and Python, counted with cloc.}",
        "\\label{tab:rq2-density}",
        "\\begin{tabular}{@{}lr" + "rr" * len(DENSITY_TOOLS) + "@{}}",
        "\\toprule",
        f"\\textbf{{Platform}} & \\textbf{{KLOC}} & {head} \\\\",
        "".join(f"\\cmidrule(lr){{{3 + 2 * i}-{4 + 2 * i}}}" for i in range(len(DENSITY_TOOLS))),
        f" & & {sub} \\\\",
        "\\midrule",
    ]
    for p in PLATFORMS:
        cells = [num(round(float(by[(p, 'combined')]["kloc"])))]
        for t, _ in DENSITY_TOOLS:
            r = by[(p, t)]
            q1, q2, q3 = quartiles(dens[(p, t)])
            cells += [f"{ratio(q2)} [{ratio(q1)}--{ratio(q3)}]", r["repos_zero"]]
        lines.append(f"{PLATFORM_NAMES[p]} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}"]
    return "\n".join(lines) + "\n"


def tukey(xs):
    """Box-plot statistics with the same quartiles as analyse.quartiles; whiskers at the most extreme
    values within 1.5 IQR of the box (Tukey), values beyond them are outliers."""
    xs = sorted(xs)
    q1, q2, q3 = quartiles(xs)
    lo_fence, hi_fence = q1 - 1.5 * (q3 - q1), q3 + 1.5 * (q3 - q1)
    inside = [x for x in xs if lo_fence <= x <= hi_fence]
    return {"q1": q1, "median": q2, "q3": q3, "lower": inside[0], "upper": inside[-1],
            "outliers": [x for x in xs if x < lo_fence or x > hi_fence]}


def rq2_boxplot(repos, tool="combined"):
    """repos: repos.csv -> pgfplots box plot of findings per KLOC per repo for each platform.
    Only the density values are written (no repository identifiers)."""
    lines = [
        "% Generated by `docker compose run --rm pipeline tables` from repos.csv; do not edit.",
        "% Needs \\usepackage{pgfplots} and \\usepgfplotslibrary{statistics}.",
        "\\begin{figure}[t]",
        "\\centering",
        "\\begin{tikzpicture}",
        "\\begin{axis}[width=\\columnwidth, height=4.6cm, boxplot/draw direction=x, xmin=0,",
        "  xlabel={Findings per KLOC}, ytick={1,2,3},",
        "  yticklabels={" + ",".join(PLATFORM_NAMES[p] for p in PLATFORMS) + "},",
        "  y dir=reverse, tick label style={font=\\footnotesize}, label style={font=\\footnotesize}]",
    ]
    for i, p in enumerate(PLATFORMS, start=1):
        st = tukey([float(r[f"density_{tool}"]) for r in repos if r["platform"] == p])
        out = " ".join(f"(0,{x:.4f})" for x in st["outliers"])
        lines += [
            f"\\addplot+[boxplot prepared={{draw position={i}, lower whisker={st['lower']:.4f}, "
            f"lower quartile={st['q1']:.4f}, median={st['median']:.4f}, upper quartile={st['q3']:.4f}, "
            f"upper whisker={st['upper']:.4f}, box extend=0.5}}, black, solid, mark=o, mark size=1.2pt]",
            f"  coordinates {{{out}}};",
        ]
    lines += [
        "\\end{axis}",
        "\\end{tikzpicture}",
        "\\caption{Findings per KLOC per repository (CodeQL and GitLab SAST combined, deduplicated; "
        "50 repositories per platform). Box: interquartile range with the median; whiskers: the most "
        "extreme values within 1.5 times the interquartile range; circles: values beyond them.}",
        "\\label{fig:rq2-density}",
        "\\end{figure}",
    ]
    return "\n".join(lines) + "\n"


def run(args):
    src = Path("/data/analysis") / args.freeze_date
    review = Path("/data/review") / args.freeze_date
    screen = Path("/data/screen") / args.freeze_date
    samples = {p: pools(read(screen / f"screen_{p}.csv"))[0] for p in PLATFORMS}
    out = Path("/tables")
    dens = read(src / "rq2_density.csv")
    totals = {r["platform"]: r["findings"] for r in dens if r["tool"] == "combined"}
    n_repos = {r["platform"]: r["repos"] for r in dens if r["tool"] == "combined"}
    repos = read(src / "repos.csv")
    outputs = {
        "rq1_category.tex": rq1_category(read(src / "rq1_category.csv"), totals, n_repos),
        "rq1_severity.tex": rq1_severity(read(src / "rq1_severity.csv")),
        "review_precision.tex": review_precision(read(review / "review_precision.csv")),
        "markers.tex": markers(samples),
        "rq2_density.tex": rq2_density(dens, repos),
    }
    for name, tex in outputs.items():
        (out / name).write_text(tex, encoding="utf-8")
        print(f"tables: wrote {out / name}")
    fig = Path("/figures") / "rq2_density_boxplot.tex"
    fig.write_text(rq2_boxplot(repos), encoding="utf-8")
    print(f"tables: wrote {fig}")
